import type { CollectionConfig } from 'payload'
import { adminOnlyFieldAccess } from '@/access/adminOnlyFieldAccess'
import { transfersAccess } from './access'
import { autoAssignSender } from './hooks/autoAssignSender'
import { setTransferDefaults } from './hooks/setTransferDefaults'
import { hashTransferPassword } from './hooks/hashTransferPassword'
import { cleanupTransferFile } from './hooks/cleanupTransferFile'
import { transferEndpoints } from './endpoints'
import { TRANSFER_EXPIRY_MS, MAX_TRANSFER_BYTES, MAX_TRANSFER_FILES } from './constants'

export const Transfers: CollectionConfig = {
  slug: 'transfers',
  admin: {
    group: 'Content',
    useAsTitle: 'filename',
    defaultColumns: ['filename', 'shareHash', 'sender', 'filesize', 'downloadCount', 'status', 'passwordEnabled', 'expiresAt'],
    description: 'Ad-hoc link transfers generated by active accounts (3-day retention).',
  },
  access: transfersAccess,
  endpoints: transferEndpoints,
  hooks: {
    beforeChange: [setTransferDefaults, hashTransferPassword],
    afterDelete: [cleanupTransferFile],
  },
  fields: [
    {
      name: 'shareHash',
      type: 'text',
      required: true,
      unique: true,
      index: true,
      admin: {
        readOnly: true,
        description: 'Unique public identifier for link generation.',
      },
    },
    {
      name: 'sender',
      type: 'relationship',
      relationTo: 'users',
      required: true,
      index: true,
      hooks: {
        beforeValidate: [autoAssignSender],
      },
      admin: {
        readOnly: true,
        position: 'sidebar',
      },
    },
    {
      name: 'filename',
      type: 'text',
      required: true,
      admin: {
        description: 'Original name of the primary uploaded deliverable (or batch label).',
      },
    },
    {
      name: 'filesize',
      type: 'number',
      required: true,
      validate: (val: any) => {
        if (typeof val !== 'number' || val <= 0) return 'Valid file size is required'
        if (val > MAX_TRANSFER_BYTES) return 'Batch exceeds 250MB transfer limit'
        return true
      },
      admin: {
        description: 'Total file size in bytes across all files (max 250MB).',
      },
    },
    {
      name: 'mimeType',
      type: 'text',
      required: true,
      defaultValue: 'application/octet-stream',
      admin: {
        description: 'MIME type of primary deliverable.',
      },
    },
    {
      name: 'storagePath',
      type: 'text',
      required: true,
      admin: {
        readOnly: true,
        description: 'Canonical storage path of primary deliverable (transfers/{userId}/{shareHash}/original/{filename}).',
      },
    },
    {
      name: 'files',
      type: 'array',
      minRows: 1,
      maxRows: MAX_TRANSFER_FILES,
      validate: (val: any) => {
        if (!val || !Array.isArray(val) || val.length === 0) {
          return true // Allow setTransferDefaults hook to backfill or validate sibling fields
        }
        if (val.length > MAX_TRANSFER_FILES) {
          return `Transfer batches cannot exceed ${MAX_TRANSFER_FILES} files.`
        }
        const totalBytes = val.reduce((acc: number, item: any) => acc + (Number(item?.filesize) || 0), 0)
        if (totalBytes > MAX_TRANSFER_BYTES) {
          return 'Total batch size exceeds 250MB transfer limit.'
        }
        return true
      },
      admin: {
        description: 'Itemized manifest of all constituent files within this transfer batch.',
      },
      fields: [
        {
          name: 'filename',
          type: 'text',
          required: true,
          admin: {
            description: 'Constituent original filename.',
          },
        },
        {
          name: 'filesize',
          type: 'number',
          required: true,
          validate: (val: any) => {
            if (typeof val !== 'number' || val <= 0) return 'Valid file size is required'
            if (val > MAX_TRANSFER_BYTES) return 'File exceeds 250MB limit'
            return true
          },
          admin: {
            description: 'Constituent file size in bytes.',
          },
        },
        {
          name: 'mimeType',
          type: 'text',
          required: true,
          defaultValue: 'application/octet-stream',
          admin: {
            description: 'Constituent MIME type.',
          },
        },
        {
          name: 'storagePath',
          type: 'text',
          required: true,
          admin: {
            readOnly: true,
            description: 'Storage path for this file in GCS / local enclave.',
          },
        },
      ],
    },
    {
      name: 'title',
      type: 'text',
      admin: {
        description: 'Optional display title shown to recipient.',
      },
    },
    {
      name: 'message',
      type: 'textarea',
      admin: {
        description: 'Optional note from sender displayed on recipient download card.',
      },
    },
    {
      name: 'status',
      type: 'select',
      defaultValue: 'active',
      options: [
        { label: 'Active', value: 'active' },
        { label: 'Revoked', value: 'revoked' },
      ],
      index: true,
      admin: {
        position: 'sidebar',
        description: 'Transfer availability state.',
      },
    },
    {
      name: 'expiresAt',
      type: 'date',
      required: true,
      index: true,
      validate: (val: any, { operation, siblingData }: any) => {
        // Allow unpopulated on create so setTransferDefaults beforeChange hook can set initial default
        if (!val) {
          if (operation === 'create') return true
          return 'Expiration timestamp is required'
        }

        const dateVal = new Date(val).getTime()
        if (Number.isNaN(dateVal)) return 'Invalid expiration date'

        // Enforce 3-day max retention ceiling from now
        const maxAllowed = Date.now() + TRANSFER_EXPIRY_MS
        if (dateVal > maxAllowed) {
          return 'Transfer expiration cannot exceed 3 days (72 hours) from now.'
        }

        return true
      },
      admin: {
        position: 'sidebar',
        description: 'Maximum 3 days from now (aligns with GCS storage retention). Default: 72 hours from creation.',
      },
    },
    {
      name: 'downloadCount',
      type: 'number',
      defaultValue: 0,
      admin: {
        position: 'sidebar',
        description: 'Number of times this transfer was downloaded.',
      },
    },
    {
      name: 'lastDownloadedAt',
      type: 'date',
      admin: {
        position: 'sidebar',
        description: 'Timestamp of the most recent download.',
      },
    },
    {
      name: 'passwordEnabled',
      type: 'checkbox',
      defaultValue: false,
      admin: {
        position: 'sidebar',
        description: 'Require password to view and download transfer.',
      },
    },
    {
      name: 'passwordHash',
      type: 'text',
      access: {
        read: adminOnlyFieldAccess,
      },
      admin: {
        hidden: true,
        description: 'Derived scrypt password hash.',
      },
    },
    {
      name: 'passwordSalt',
      type: 'text',
      access: {
        read: adminOnlyFieldAccess,
      },
      admin: {
        hidden: true,
        description: 'Salt for scrypt password hashing.',
      },
    },
    {
      name: 'passwordVersion',
      type: 'number',
      defaultValue: 0,
      admin: {
        readOnly: true,
        position: 'sidebar',
        description: 'Incremented on password change to invalidate outstanding tokens.',
      },
    },
    {
      name: '_password',
      type: 'text',
      virtual: true,
      admin: {
        hidden: true,
        description: 'Transient input field for password setting/updating.',
      },
    },
  ],
  timestamps: true,
}
