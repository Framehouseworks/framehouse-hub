import type { CollectionConfig } from 'payload'
import { transfersAccess } from './access'
import { autoAssignSender } from './hooks/autoAssignSender'
import { setTransferDefaults } from './hooks/setTransferDefaults'
import { cleanupTransferFile } from './hooks/cleanupTransferFile'
import { transferEndpoints } from './endpoints'
import { TRANSFER_EXPIRY_MS, MAX_TRANSFER_BYTES } from './constants'

export const Transfers: CollectionConfig = {
  slug: 'transfers',
  admin: {
    group: 'Content',
    useAsTitle: 'filename',
    defaultColumns: ['filename', 'shareHash', 'sender', 'filesize', 'downloadCount', 'status', 'expiresAt'],
    description: 'Ad-hoc link transfers generated by active accounts (3-day retention).',
  },
  access: transfersAccess,
  endpoints: transferEndpoints,
  hooks: {
    beforeChange: [setTransferDefaults],
    afterDelete: [cleanupTransferFile],
  },
  fields: [
    {
      name: 'shareHash',
      type: 'text',
      required: true,
      unique: true,
      index: true,
      admin: {
        readOnly: true,
        description: 'Unique public identifier for link generation.',
      },
    },
    {
      name: 'sender',
      type: 'relationship',
      relationTo: 'users',
      required: true,
      index: true,
      hooks: {
        beforeValidate: [autoAssignSender],
      },
      admin: {
        readOnly: true,
        position: 'sidebar',
      },
    },
    {
      name: 'filename',
      type: 'text',
      required: true,
      admin: {
        description: 'Original name of the uploaded deliverable.',
      },
    },
    {
      name: 'filesize',
      type: 'number',
      required: true,
      validate: (val: any) => {
        if (typeof val !== 'number' || val <= 0) return 'Valid file size is required'
        if (val > MAX_TRANSFER_BYTES) return 'File exceeds 250MB transfer limit'
        return true
      },
      admin: {
        description: 'File size in bytes (max 250MB).',
      },
    },
    {
      name: 'mimeType',
      type: 'text',
      required: true,
      defaultValue: 'application/octet-stream',
      admin: {
        description: 'MIME type of the uploaded file.',
      },
    },
    {
      name: 'storagePath',
      type: 'text',
      required: true,
      admin: {
        readOnly: true,
        description: 'Canonical storage path (transfers/{userId}/{shareHash}/original/{filename}).',
      },
    },
    {
      name: 'title',
      type: 'text',
      admin: {
        description: 'Optional display title shown to recipient.',
      },
    },
    {
      name: 'message',
      type: 'textarea',
      admin: {
        description: 'Optional note from sender displayed on recipient download card.',
      },
    },
    {
      name: 'status',
      type: 'select',
      defaultValue: 'active',
      options: [
        { label: 'Active', value: 'active' },
        { label: 'Revoked', value: 'revoked' },
      ],
      index: true,
      admin: {
        position: 'sidebar',
        description: 'Transfer availability state.',
      },
    },
    {
      name: 'expiresAt',
      type: 'date',
      required: true,
      index: true,
      validate: (val: any, { operation, siblingData }: any) => {
        // Allow unpopulated on create so setTransferDefaults beforeChange hook can set initial default
        if (!val) {
          if (operation === 'create') return true
          return 'Expiration timestamp is required'
        }

        const dateVal = new Date(val).getTime()
        if (Number.isNaN(dateVal)) return 'Invalid expiration date'

        // Enforce 3-day max retention ceiling from now
        const maxAllowed = Date.now() + TRANSFER_EXPIRY_MS
        if (dateVal > maxAllowed) {
          return 'Transfer expiration cannot exceed 3 days (72 hours) from now.'
        }

        return true
      },
      admin: {
        position: 'sidebar',
        description: 'Maximum 3 days from now (aligns with GCS storage retention). Default: 72 hours from creation.',
      },
    },
    {
      name: 'downloadCount',
      type: 'number',
      defaultValue: 0,
      admin: {
        position: 'sidebar',
        description: 'Number of times this transfer was downloaded.',
      },
    },
    {
      name: 'lastDownloadedAt',
      type: 'date',
      admin: {
        position: 'sidebar',
        description: 'Timestamp of the most recent download.',
      },
    },
  ],
  timestamps: true,
}
